def _source_status(state: State | None) -> str:
    """Classify one source: missing, unavailable, unknown or available."""
    if state is None:
        return "missing"
    if state.state == STATE_UNAVAILABLE:
        return "unavailable"
    if state.state == STATE_UNKNOWN:
        return "unknown"
    return "available"


def _status_of(source: dict[str, Any]) -> str:
    """Return a source status; sources without it fall back to ``available``."""
    status = source.get("status")
    if isinstance(status, str):
        return status
    return "available" if source.get("available") else "unavailable"


def _dark_source_id(area: AdaptiveArea) -> str | None:
    """Return the numeric brightness sensor that the Area brightness is derived from.

    The same resolution as the Light decision and the Dark state (helpers/sources.py).
    """
    return light_illuminance_entity_id(area)


def _brightness_reason(dark_source: dict[str, Any] | None) -> str:
    """Explain where the dark/bright state comes from, without inventing a source."""
    if dark_source is None:
        return "not_configured"
    if dark_source.get("status") == "missing":
        return "source_missing"
    if not dark_source.get("available"):
        return "source_unavailable"
    return "configured_source"


def _state_data(state: State | None, entity_id: str) -> dict[str, Any]:
    """Return an explicit, JSON-safe view of one entity state.

    ``status`` distinguishes missing, unavailable and unknown sources, which
    ``available`` and ``state`` cannot (both are false/null for the last two).
    """
    if state is None:
        return {
            "entity_id": entity_id,
            "state": None,
            "available": False,
            "status": "missing",
        }
    return {
        "status": _source_status(state),
        "entity_id": entity_id,
        "name": state.attributes.get(ATTR_FRIENDLY_NAME, entity_id),
        "state": (
            None if state.state in (STATE_UNAVAILABLE, STATE_UNKNOWN) else state.state
        ),
        "available": state.state not in (STATE_UNAVAILABLE, STATE_UNKNOWN),
        "device_class": state.attributes.get(ATTR_DEVICE_CLASS),
        "unit": state.attributes.get(ATTR_UNIT_OF_MEASUREMENT),
    }


def _area_sources(area: AdaptiveArea) -> list[str]:
    """Return the known source IDs without discovering unrelated HA entities."""
    return sorted(
        entity["entity_id"]
        for entities in area.entities.values()
        for entity in entities
        if "entity_id" in entity
    )


def _generated_states(hass: HomeAssistant, area: AdaptiveArea) -> list[dict[str, Any]]:
    """Return states generated by this config entry."""
    return [
        _state_data(hass.states.get(entry.entity_id), entry.entity_id)
        for entry in sorted(
            generated_entities_for_area(hass, area), key=lambda entry: entry.entity_id
        )
    ]


def _aggregates(hass: HomeAssistant, area: AdaptiveArea) -> list[dict[str, Any]]:
    """Map aggregate entities and their known sources for the panel."""
    sources = _area_sources(area)
    result = []
    for aggregate in _generated_states(hass, area):
        state = hass.states.get(aggregate["entity_id"])
        if state is None or "source_count" not in state.attributes:
            continue
        device_class = state.attributes.get("source_device_class") or aggregate.get(
            "device_class"
        )
        aggregate_sources = [
            _state_data(hass.states.get(entity_id), entity_id)
            for entity_id in sources
            if (source_state := hass.states.get(entity_id)) is not None
            and source_state.attributes.get(ATTR_DEVICE_CLASS) == device_class
        ]
        result.append(
            {
                **aggregate,
                "source_count": state.attributes.get("source_count"),
                "available_count": state.attributes.get("available_count"),
                "unavailable_count": state.attributes.get("unavailable_count"),
                "sources": aggregate_sources,
            }
        )
    return result


def _light_groups(hass: HomeAssistant, area: AdaptiveArea) -> list[dict[str, Any]]:
    """Map configured light groups; absent groups remain absent."""
    config = area.feature_config("light_groups")
    groups = []
    for key, label in _LIGHT_GROUPS.items():
        entity_ids = config.get(key, [])
        if not entity_ids:
            continue
        states = [hass.states.get(entity_id) for entity_id in entity_ids]
        groups.append(
            {
                "id": key,
                "name": label,
                "on": sum(
                    state is not None and state.state == STATE_ON for state in states
                ),
                "total": len(entity_ids),
                "sources": [
                    _state_data(hass.states.get(entity_id), entity_id)
                    for entity_id in entity_ids
                ],
            }
        )
    return groups


def _control(hass: HomeAssistant, entity_id: str) -> dict[str, Any]:
    """Map one explicitly configured light or integration switch control."""
    state = hass.states.get(entity_id)
    domain = entity_id.split(".", 1)[0]
    return {
        "entity_id": entity_id,
        "name": (
            state.attributes.get(ATTR_FRIENDLY_NAME, entity_id) if state else entity_id
        ),
        "domain": domain,
        "state": state.state if state else None,
        "available": state is not None
        and state.state not in (STATE_UNAVAILABLE, STATE_UNKNOWN),
        "controllable": domain in {"light", "switch"},
        "actions": ["turn_on", "turn_off"],
        "icon": state.attributes.get(ATTR_ICON) if state else None,
    }


def _controls(hass: HomeAssistant, area: AdaptiveArea) -> list[dict[str, Any]]:
    """Return deduplicated controls already assigned to a non-meta Area."""
    if area.is_meta():
        return []
    seen: set[str] = set()
    groups = []
    for group in _light_groups(hass, area):
        controls = [
            _control(hass, entity_id)
            for entity_id in area.feature_config("light_groups").get(group["id"], [])
            if entity_id not in seen and not seen.add(entity_id)
        ]
        if controls:
            groups.append(
                {"id": group["id"], "name": group["name"], "controls": controls}
            )
    switches = [
        _control(hass, entry["entity_id"])
        for entry in area.adaptive_entities.get("switch", [])
        if entry.get("entity_id") not in seen and not seen.add(entry["entity_id"])
    ]
    if switches:
        groups.append({"id": "switches", "name": "Controls", "controls": switches})
    return groups


_ENVIRONMENT_VALUES = (
    "temperature",
    "humidity",
    "comfort",
    "air_quality",
    "mould_risk",
    "notices",
)


# A generated environment state is shown when it carries a value or a notice.
_ENVIRONMENT_MARKERS = ("comfort", "humidity", "air_quality", "mould_risk", "notices")


def _environment(
    hass: HomeAssistant, area: AdaptiveArea, include_entities: bool = True
) -> dict[str, Any] | None:
    """Return the public environment presentation, if the feature has data.

    Non-administrators receive the values only: no entity fields of the generated
    entity and no ``used_sensors`` (a list of entity IDs).
    """
    for entity in _generated_states(hass, area):
        state = hass.states.get(entity["entity_id"])
        if state is None or not any(
            key in state.attributes for key in _ENVIRONMENT_MARKERS
        ):
            continue
        values = {
            key: state.attributes[key]
            for key in _ENVIRONMENT_VALUES
            if key in state.attributes
        }
        if not include_entities:
            return values
        return {
            **entity,
            **values,
            **(
                {"used_sensors": state.attributes["used_sensors"]}
                if "used_sensors" in state.attributes
                else {}
            ),
        }
    return None


def _source_coverage(hass: HomeAssistant, entity_ids: list[str]) -> dict[str, int]:
    """Return the availability of already configured area sources."""
    states = [
        _state_data(hass.states.get(entity_id), entity_id) for entity_id in entity_ids
    ]
    return {
        "available": sum(state["available"] for state in states),
        "total": len(states),
    }


def _room_usage(area: AdaptiveArea) -> dict[str, Any] | None:
    """Return current, already calculated usage values."""
    if area.room_usage is None:
        return None
    assessment = area.room_usage.assessment
    return {
        key: assessment[key]
        for key in (
            "presence_minutes_since_cleaning",
            "current_occupancy_duration_seconds",
        )
        if key in assessment
    }


def _cleaning(area: AdaptiveArea) -> dict[str, Any] | None:
    """Return the existing cleaning assessment without recomputing it."""
    if area.room_usage is None:
        return None
    assessment = area.room_usage.assessment
    return {
        key: str(assessment[key]) if key == "cleaning_state" else assessment[key]
        for key in ("cleaning_state", "due", "remaining_minutes_to_due")
        if key in assessment
    }


def _floor_name(hass: HomeAssistant, floor_id: str | None) -> str | None:
    """Return the floor name from the registry, or None when it is unknown."""
    if not floor_id:
        return None
    floor = async_get_floor_registry(hass).async_get_floor(floor_id)
    return floor.name if floor is not None else None


def _meta_members(hass: HomeAssistant, area: AdaptiveArea) -> list[str]:
    """Return the IDs of loaded physical Areas that a Meta-Area aggregates.

    Only Areas that are loaded are listed; a configured child that is not loaded
    is omitted rather than invented.
    """
    children = set(getattr(area, "child_areas", []) or [])
    return sorted(
        str(member.id)
        for member in _areas(hass)
        if not member.is_meta() and member.slug in children
    )


def _presence_state(
    hass: HomeAssistant, area: AdaptiveArea, coverage: dict[str, int]
) -> str:
    """Return occupied, clear or unknown for the dashboard.

    `is_occupied()` stays the decision of the existing automation (including a
    valid Presence Hold or a timeout). Without such a decision, a Physical Area
    is clear only if at least one of its own presence sources is available;
    otherwise the state is unknown and is never counted as clear. A Meta-Area is
    clear only if every loaded member is clear.
    """
    if area.is_occupied():
        return "occupied"
    if not area.is_meta():
        return "clear" if coverage["available"] > 0 else "unknown"
    member_ids = set(_meta_members(hass, area))
    if not member_ids:
        return "unknown"
    members = [
        member
        for member in _areas(hass)
        if not member.is_meta() and str(member.id) in member_ids
    ]
    states = [
        _presence_state(
            hass,
            member,
            _source_coverage(hass, member.get_presence_sensors()),
        )
        for member in members
    ]
    if len(states) != len(member_ids):
        return "unknown"
    if "occupied" in states:
        return "occupied"
    return "clear" if all(state == "clear" for state in states) else "unknown"


def build_area_summary(
    hass: HomeAssistant, area: AdaptiveArea, include_entities: bool = True
) -> dict[str, Any]:
    """Build the compact stable DTO used by the overview and update events.

    Entity identifiers (controls) are only included for administrators.
    Source coverage is always an aggregate.
    """
    aggregates = _aggregates(hass, area)
    illuminance = next(
        (item for item in aggregates if item.get("device_class") == "illuminance"), None
    )
    groups = _light_groups(hass, area)
    presence_sources = area.get_presence_sensors()
    sources = _area_sources(area)
    brightness_state = (
        AREA_STATE_BRIGHT
        if area.has_state(AREA_STATE_BRIGHT)
        else AREA_STATE_DARK if area.has_state(AREA_STATE_DARK) else None
    )
    aggregate_warnings = sum(
        aggregate.get("source_count") == 0 for aggregate in aggregates
    )
    # The dark state is derived from the same numeric source: no separate consistency case.
    secondary_state_warnings = 0
    warning_count = aggregate_warnings
    return {
        "id": str(area.id),
        "name": area.name,
        "type": "meta" if area.is_meta() else "area",
        # Floor metadata from the Home Assistant registry; null means no floor or
        # an unknown floor. Floor IDs and names are not entity identifiers.
        "floor_id": area.floor_id,
        "floor_name": _floor_name(hass, area.floor_id),
        **(
            {
                "members": _meta_members(hass, area),
                # Configured children; fewer loaded members mean the Meta-Area is partial.
                "members_total": len(getattr(area, "child_areas", []) or []),
            }
            if area.is_meta()
            else {}
        ),
        "occupied": area.is_occupied(),
        "active_states": sorted(str(state) for state in area.states),
        "presence": {
            "state": _presence_state(
                hass, area, _source_coverage(hass, presence_sources)
            ),
            **_source_coverage(hass, presence_sources),
        },
        "brightness": (
            {
                "state": brightness_state,
                "illuminance": illuminance.get("state") if illuminance else None,
                "unit": illuminance.get("unit") if illuminance else None,
            }
            if illuminance
            or area.has_state(AREA_STATE_BRIGHT)
            or area.has_state(AREA_STATE_DARK)
            else None
        ),
        "warning_count": warning_count,
        # Attribution by source: aggregates belong to the aggregates feature, the dark
        # source belongs to the secondary states (no feature flag). Kept additive.
        "warning_details": {
            "aggregates": aggregate_warnings,
            "secondary_states": secondary_state_warnings,
        },
        "lights": (
            {
                "on": sum(group["on"] for group in groups),
                "total": sum(group["total"] for group in groups),
                # Group names and per-group counts are light runtime detail: administrators only.
                **(
                    {
                        "groups": [
                            {key: group[key] for key in ("id", "name", "on", "total")}
                            for group in groups
                        ]
                    }
                    if include_entities
                    else {}
                ),
            }
            if groups
            else None
        ),
        "environment": _environment(hass, area, include_entities),
        "room_usage": _room_usage(area),
        "cleaning": _cleaning(area),
        "sources": _source_coverage(hass, sources),
        "enabled_features": sorted(area.config.get(CONF_ENABLED_FEATURES, {})),
        **({"controls": _controls(hass, area)} if include_entities else {}),
    }


def _aggregate_without_entities(aggregate: dict[str, Any]) -> dict[str, Any]:
    """Return an aggregate for non-administrators: counts only, no entity IDs."""
    sources = aggregate.get("sources", [])
    return {
        key: value
        for key, value in aggregate.items()
        if key not in ("entity_id", "sources")
    } | {
        "sources": {
            "total": len(sources),
            "available": sum(bool(source.get("available")) for source in sources),
        }
    }


def build_area_detail(
    hass: HomeAssistant, area: AdaptiveArea, include_entities: bool = True
) -> dict[str, Any]:
    """Build a read-only area DTO from current runtime data.

    Non-administrators receive aggregated counts instead of entity identifiers
    and no light-group or control detail.
    """
    summary = build_area_summary(hass, area, include_entities)
    aggregates = _aggregates(hass, area)
    dark_source_id = _dark_source_id(area)
    if not include_entities:
        return {
            **summary,
            "presence": {
                "occupied": area.is_occupied(),
                "state": _presence_state(
                    hass,
                    area,
                    _source_coverage(hass, area.get_presence_sensors()),
                ),
                "sources": _source_coverage(hass, area.get_presence_sensors()),
            },
            "brightness_detail": {
                "state": summary["brightness"],
                "reason": "not_available_without_entities",
                "default_dark": False,
            },
            "aggregates": [_aggregate_without_entities(item) for item in aggregates],
            "environment": _environment(hass, area, include_entities=False),
            "sources": _source_coverage(hass, _area_sources(area)),
        }
    dark_source_data = (
        _state_data(hass.states.get(dark_source_id), dark_source_id)
        if dark_source_id
        else None
    )
    return {
        **summary,
        "presence": {
            "occupied": area.is_occupied(),
            "state": _presence_state(
                hass, area, _source_coverage(hass, area.get_presence_sensors())
            ),
            "sources": [
                _state_data(hass.states.get(source), source)
                for source in area.get_presence_sensors()
            ],
        },
        "brightness_detail": {
            "state": summary["brightness"],
            "dark_source": dark_source_data,
            "reason": _brightness_reason(dark_source_data),
            "default_dark": dark_source_id is None and area.has_state(AREA_STATE_DARK),
        },
        "light_groups": _light_groups(hass, area),
        "aggregates": aggregates,
        "environment": _environment(hass, area),
        "sources": [
            _state_data(hass.states.get(source), source)
            for source in _area_sources(area)
        ],
        "controls": summary["controls"],
    }


