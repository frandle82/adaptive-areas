def _allowed(value: Any, allowed: frozenset[str]) -> str:
    return value if isinstance(value, str) and value in allowed else "other"


def _trace_timestamp(value: Any) -> str | None:
    """Return the timestamp only when it is a valid ISO-8601 UTC value."""
    if not isinstance(value, str):
        return None
    try:
        datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    return value


def _trace_entry(entry: dict[str, Any]) -> dict[str, Any]:
    """Map one stored trace entry to the public DTO through allowlists."""
    raw_states = entry.get("area_state") or []
    raw_reasons = entry.get("reason_codes") or []
    raw_count = entry.get("target_count", 0)
    exception = entry.get("exception_class")
    return {
        "timestamp": _trace_timestamp(entry.get("timestamp")),
        "feature": _allowed(entry.get("feature"), TRACE_FEATURES),
        "trigger": _allowed(entry.get("trigger"), TRACE_TRIGGERS),
        "area_state": [
            state
            for state in (raw_states if isinstance(raw_states, list) else [])
            if state in TRACE_STATES
        ][:10],
        "decision": _allowed(entry.get("decision"), TRACE_DECISIONS),
        "outcome": _allowed(entry.get("outcome"), TRACE_OUTCOMES),
        "reason_codes": [
            code
            for code in (raw_reasons if isinstance(raw_reasons, list) else [])
            if code in TRACE_REASON_CODES
        ][:5],
        "target_count": (
            min(raw_count, _TRACE_MAX_TARGETS)
            if isinstance(raw_count, int) and raw_count >= 0
            else 0
        ),
        "from": entry.get("from") if entry.get("from") in TRACE_STATES else None,
        "to": entry.get("to") if entry.get("to") in TRACE_STATES else None,
        "exception_class": (
            exception
            if isinstance(exception, str) and _EXCEPTION_NAME.match(exception)
            else None
        ),
        "group": _allowed_group(entry.get("group")),
    }


def _allowed_group(value: Any) -> str | None:
    """Return a light group category of a trace entry, or None."""
    return value if isinstance(value, str) and value in TRACE_GROUPS else None


def _last_group_decision(area: AdaptiveArea, category: str) -> dict[str, Any] | None:
    """Return the newest traced decision of one light group, or None.

    Read from the Area's bounded in-memory trace; an older decision may have left it.
    """
    trace = getattr(area, "decision_trace", None)
    if trace is None:
        return None
    for entry in reversed(trace.export()):
        if entry.get("feature") == "light_groups" and entry.get("group") == category:
            public = _trace_entry(entry)
            return {
                key: public[key]
                for key in (
                    "timestamp",
                    "trigger",
                    "decision",
                    "outcome",
                    "reason_codes",
                )
            }
    return None


def _group_runtime(
    area: AdaptiveArea, category: str, state: State | None
) -> dict[str, Any]:
    """Runtime view of one group from its own attributes and the trace (no new state)."""
    attributes = state.attributes if state is not None else {}
    return {
        "controlling": (
            attributes.get("controlling")
            if isinstance(attributes.get("controlling"), bool)
            else None
        ),
        "manual_override": (
            attributes.get(ATTR_MANUAL_OVERRIDE)
            if isinstance(attributes.get(ATTR_MANUAL_OVERRIDE), bool)
            else None
        ),
        "last_decision": _last_group_decision(area, str(category)),
    }


def build_decision_trace(area: AdaptiveArea, limit: int = 20) -> dict[str, Any]:
    """Return the newest decisions of one area from its in-memory ring buffer.

    The buffer keeps at most DEFAULT_TRACE_LENGTH entries. Nothing is persisted.
    """
    limit = max(1, min(int(limit), 20))
    entries = area.decision_trace.export()[-limit:]
    entries.reverse()
    return {
        "area_id": str(area.id),
        "limit": limit,
        "entries": [_trace_entry(entry) for entry in entries],
    }


def _light_group_entity_id(hass: HomeAssistant, area: AdaptiveArea, category) -> str:
    """Return the registered entity ID of one of the Area's light groups."""
    return resolve_generated_entity_id(
        hass,
        AdaptiveAreasFeatureInfoLightGroups,
        LIGHT_DOMAIN,
        area.slug,
        str(category),
    )


def _live_state(hass: HomeAssistant, entity_id: str) -> State | None:
    """Return the state of a loaded entity, or None.

    A registry entry without a loaded entity keeps a restored placeholder state
    (`restored: true`). Such a group does not exist at runtime and is not controllable.
    """
    state = hass.states.get(entity_id)
    if state is None or state.attributes.get("restored") is True:
        return None
    return state


def light_group_diagnostics(
    hass: HomeAssistant, area: AdaptiveArea
) -> list[dict[str, Any]]:
    """Read-only view of the native light groups of one Area.

    Uses the existing group entities and their attributes, and the existing helpers that
    decide which lights are group-owned. It computes no control decision of its own.
    """
    feature = area.feature_config(CONF_FEATURE_LIGHT_GROUPS) or {}
    groups: list[dict[str, Any]] = []
    for category in LIGHT_GROUP_CATEGORIES:
        configured = [str(item) for item in (feature.get(category) or [])]
        entity_id = _light_group_entity_id(hass, area, category)
        state = _live_state(hass, entity_id)
        activation = feature.get(
            LIGHT_GROUP_ACTIVATION[category],
            LIGHT_GROUP_ACTIVATION_DEFAULTS[category],
        )
        groups.append(
            {
                "category": category,
                "activation": activation,
                "configured_count": len(configured),
                "entity_id": entity_id if state is not None else None,
                "state": state.state if state is not None else None,
                "members": (
                    list(state.attributes.get("lights", []))
                    if state is not None
                    else []
                ),
                "members_resolved": state is not None,
                "ownership_blocked": bool(
                    state is not None and group_is_blocked(hass, entity_id, configured)
                ),
                **_group_runtime(area, category, state),
            }
        )
    all_entity_id = _light_group_entity_id(hass, area, LightGroupCategory.ALL)
    all_state = _live_state(hass, all_entity_id)
    all_members = [
        str(item)
        for category in LIGHT_GROUP_CATEGORIES
        for item in (feature.get(category) or [])
    ]
    groups.append(
        {
            "category": LightGroupCategory.ALL,
            "activation": None,
            "configured_count": len(dict.fromkeys(all_members)),
            "entity_id": all_entity_id if all_state is not None else None,
            "state": all_state.state if all_state is not None else None,
            "members": (
                list(all_state.attributes.get("lights", []))
                if all_state is not None
                else []
            ),
            "members_resolved": all_state is not None,
            "ownership_blocked": bool(
                all_state is not None
                and group_is_blocked(hass, all_entity_id, all_members)
            ),
            **_group_runtime(area, LightGroupCategory.ALL, all_state),
        }
    )
    return groups


def build_light_runtime_status(
    hass: HomeAssistant, area: AdaptiveArea
) -> dict[str, Any]:
    """Build a read-only snapshot of the Light section of one Area form.

    Shows the presence and brightness inputs, the thresholds and the automatic group control
    (native light groups, see control_path). Lights that belong to no group are not controlled
    automatically and are therefore not listed as a control path.
    """
    if not area.has_feature(CONF_FEATURE_LIGHT):
        return {"area_id": str(area.id), "light": {"enabled": False}}

    light_feature = area.feature_config(CONF_FEATURE_LIGHT) or {}
    thresholds = {
        "turn_on_below": light_feature.get("turn_on_below"),
        "turn_off_above": light_feature.get("turn_off_above"),
    }
    groups = light_group_diagnostics(hass, area)
    group_active = any(
        group["category"] != LightGroupCategory.ALL
        and group["entity_id"] is not None
        and group["activation"] != LIGHT_GROUP_ACTIVATION_DISABLED
        and group["configured_count"] > 0
        for group in groups
    )
    manual_groups = [
        group["entity_id"]
        for group in groups
        if group["entity_id"] is not None
        and _group_manual_override(hass, group["entity_id"])
    ]
    snapshot = light_source_snapshot(area)
    if snapshot is None:
        presence = {"available": False, "occupied": None}
        illuminance = {
            "configured": False,
            "entity_id": None,
            "available": False,
            "value": None,
        }
    else:
        presence = {
            "available": snapshot.presence_available,
            "occupied": snapshot.presence_state,
        }
        illuminance = {
            "configured": snapshot.illuminance_entity_id is not None,
            "entity_id": snapshot.illuminance_entity_id,
            "available": snapshot.illuminance_available,
            "value": snapshot.illuminance_value,
        }
    return {
        "area_id": str(area.id),
        "light": {
            "enabled": True,
            "presence": presence,
            "illuminance": illuminance,
            "thresholds": thresholds,
            # A group is overridden after a manual change of its members (CLEAR ends it).
            "override": {
                "mode": "MANUAL" if manual_groups else "NONE",
                "groups": manual_groups,
            },
            "control_path": {
                "group_active": group_active,
                "groups": groups,
                # The Area's actual light control switch, as the groups read it.
                "control_switch": _light_control_switch(area),
            },
        },
    }


def _light_control_switch(area: AdaptiveArea) -> dict[str, Any]:
    """Return the registered light control switch of an Area and whether it is on."""
    switch = getattr(area, "light_control_switch", None)
    return {
        "entity_id": switch.entity_id if switch is not None else None,
        "enabled": bool(switch is not None and switch.is_on),
    }


def _group_manual_override(hass: HomeAssistant, entity_id: str) -> bool:
    """Return whether a native light group reports a manual override."""
    state = hass.states.get(entity_id)
    return state is not None and state.attributes.get(ATTR_MANUAL_OVERRIDE) is True


def build_climate_runtime_status(
    hass: HomeAssistant, area: AdaptiveArea
) -> dict[str, Any]:
    """Build a read-only Climate Control runtime snapshot for one Area."""
    enabled = area.has_feature(CONF_FEATURE_CLIMATE_CONTROL)
    config = area.feature_config(CONF_FEATURE_CLIMATE_CONTROL) if enabled else {}
    target_entity = config.get(CONF_CLIMATE_CONTROL_ENTITY_ID)
    target_state = hass.states.get(target_entity) if target_entity else None
    target_available = target_state is not None and target_state.state not in (
        STATE_UNAVAILABLE,
        STATE_UNKNOWN,
    )
    relevant_states = [
        str(state)
        for state in area.states
        if state
        in {
            AreaStates.CLEAR,
            AreaStates.SLEEP,
            AreaStates.EXTENDED,
            AreaStates.OCCUPIED,
        }
    ]
    controller = getattr(area, "climate_control_switch", None) if enabled else None
    controller_on = bool(controller and controller.is_on)
    decision, configured_preset = (
        controller.runtime_decision() if controller else ("no_action", None)
    )
    return {
        "area_id": str(area.id),
        "enabled": enabled,
        "controller_on": controller_on,
        "target_entity": target_entity,
        "target_available": target_available,
        "area_states": relevant_states,
        "current_preset": (
            target_state.attributes.get(ATTR_PRESET_MODE) if target_available else None
        ),
        "occupancy_threshold": (
            config.get(
                CONF_CLIMATE_CONTROL_OCCUPANCY_THRESHOLD,
                DEFAULT_CLIMATE_CONTROL_OCCUPANCY_THRESHOLD,
            )
            if enabled
            else None
        ),
        "occupancy_pending": bool(controller and controller.occupancy_pending),
        "decision": decision,
        "configured_preset": configured_preset,
    }


def _areas(hass: HomeAssistant) -> Iterable[AdaptiveArea]:
    """Yield loaded areas only."""
    yield from iter_runtime_areas(hass)


def _count_presence(summaries: list[dict[str, Any]], state: str) -> int:
    """Count physical Areas with the given presence state (Meta-Areas excluded)."""
    return sum(
        1
        for summary in summaries
        if summary.get("type") != "meta"
        and (summary.get("presence") or {}).get("state") == state
    )


def build_overview(
    hass: HomeAssistant, include_entities: bool = True
) -> dict[str, Any]:
    """Build the complete lightweight overview without global entity discovery."""
    areas = sorted(_areas(hass), key=lambda area: area.name.casefold())
    summaries = [build_area_summary(hass, area, include_entities) for area in areas]
    return {
        "areas": summaries,
        "enabled_feature_tabs": sorted(
            {
                feature
                for summary in summaries
                for feature in summary["enabled_features"]
            }
        ),
        "counts": {
            "areas": sum(not area.is_meta() for area in areas),
            "meta_areas": sum(area.is_meta() for area in areas),
            # Legacy semantics (automation decision, includes Meta-Areas); kept unchanged.
            "occupied": sum(area.is_occupied() for area in areas),
            # Physical Areas only, same presence semantics as the Area cards.
            "physical_occupied": _count_presence(summaries, "occupied"),
            "physical_clear": _count_presence(summaries, "clear"),
            "physical_unknown": _count_presence(summaries, "unknown"),
            "dark": sum(area.has_state(AREA_STATE_DARK) for area in areas),
            "bright": sum(area.has_state(AREA_STATE_BRIGHT) for area in areas),
            "lights_on": sum((item["lights"] or {}).get("on", 0) for item in summaries),
        },
    }


def build_diagnostics(hass: HomeAssistant, version: str | None) -> dict[str, Any]:
    """Report simple read-only dashboard diagnostics."""
    areas = list(_areas(hass))
    issues = []
    adaptive_entity_count = 0
    unavailable = 0
    unknown_sources = 0
    for area in areas:
        try:
            detail = build_area_detail(hass, area)
        except Exception:  # Diagnostics must not hide every other Area.
            _LOGGER.exception(
                "Unable to build dashboard diagnostics for area %s", area.id
            )
            issues.append(
                {
                    "severity": "warning",
                    "area_id": str(area.id),
                    "code": "diagnostics_unavailable",
                    "message": "Some diagnostics are unavailable.",
                }
            )
            continue
        adaptive_entity_count += len(_generated_states(hass, area))
        # Unknown sources are not technical faults: they are counted separately.
        unavailable += sum(
            _status_of(source) in ("unavailable", "missing")
            for source in detail["sources"]
        )
        unknown_sources += sum(
            _status_of(source) == "unknown" for source in detail["sources"]
        )
        for aggregate in detail["aggregates"]:
            if aggregate["source_count"] == 0:
                issues.append(
                    {
                        "severity": "warning",
                        "area_id": detail["id"],
                        "code": "empty_aggregate",
                        "message": "Aggregate has no sources.",
                    }
                )

        issues.extend(
            {
                "severity": "warning",
                "area_id": detail["id"],
                "code": "unavailable_source",
                "message": "A source is unavailable.",
            }
            for source in detail["sources"]
            if _status_of(source) in ("unavailable", "missing")
        )
        # Informational only: an unknown state is not reported as a fault.
        issues.extend(
            {
                "severity": "info",
                "area_id": detail["id"],
                "code": "unknown_source",
                "message": "A source state is unknown.",
            }
            for source in detail["sources"]
            if _status_of(source) == "unknown"
        )
    return {
        "version": version,
        "area_count": sum(not area.is_meta() for area in areas),
        "meta_area_count": sum(area.is_meta() for area in areas),
        "adaptive_entity_count": adaptive_entity_count,
        "unavailable_source_count": unavailable,
        "unknown_source_count": unknown_sources,
        # False while any source state is unknown or an Area's diagnostics failed:
        # an empty issue list then says nothing about completeness.
        "data_complete": unknown_sources == 0
        and not any(issue["code"] == "diagnostics_unavailable" for issue in issues),
        "empty_aggregate_count": sum(
            issue["code"] == "empty_aggregate" for issue in issues
        ),
        "warning_count": sum(issue["severity"] == "warning" for issue in issues),
        "issues": issues,
    }
