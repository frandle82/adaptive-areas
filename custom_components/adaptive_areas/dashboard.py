_LIGHT_GROUPS = {
    CONF_OVERHEAD_LIGHTS: "Overhead",
    CONF_TASK_LIGHTS: "Task",
    CONF_ACCENT_LIGHTS: "Accent",
    CONF_SLEEP_LIGHTS: "Sleep",
}
_LOGGER = logging.getLogger(__name__)


def _state_data(state: State | None, entity_id: str) -> dict[str, Any]:
    """Return an explicit, JSON-safe view of one entity state."""
    if state is None:
        return {"entity_id": entity_id, "state": None, "available": False}
    return {
        "entity_id": entity_id,
        "name": state.attributes.get(ATTR_FRIENDLY_NAME, entity_id),
        "state": (
            None if state.state in (STATE_UNAVAILABLE, STATE_UNKNOWN) else state.state
        ),
        "available": state.state not in (STATE_UNAVAILABLE, STATE_UNKNOWN),
        "device_class": state.attributes.get(ATTR_DEVICE_CLASS),
        "unit": state.attributes.get(ATTR_UNIT_OF_MEASUREMENT),
    }


def _area_sources(area: AdaptiveArea) -> list[str]:
    """Return the known source IDs without discovering unrelated HA entities."""
    return sorted(
        entity["entity_id"]
        for entities in area.entities.values()
        for entity in entities
        if "entity_id" in entity
    )


def _generated_states(hass: HomeAssistant, area: AdaptiveArea) -> list[dict[str, Any]]:
    """Return states generated by this config entry."""
    return [
        _state_data(hass.states.get(entry.entity_id), entry.entity_id)
        for entry in sorted(
            generated_entities_for_area(hass, area), key=lambda entry: entry.entity_id
        )
    ]


def _aggregates(hass: HomeAssistant, area: AdaptiveArea) -> list[dict[str, Any]]:
    """Map aggregate entities and their known sources for the panel."""
    sources = _area_sources(area)
    result = []
    for aggregate in _generated_states(hass, area):
        state = hass.states.get(aggregate["entity_id"])
        if state is None or "source_count" not in state.attributes:
            continue
        device_class = state.attributes.get("source_device_class") or aggregate.get(
            "device_class"
        )
        aggregate_sources = [
            _state_data(hass.states.get(entity_id), entity_id)
            for entity_id in sources
            if (source_state := hass.states.get(entity_id)) is not None
            and source_state.attributes.get(ATTR_DEVICE_CLASS) == device_class
        ]
        result.append(
            {
                **aggregate,
                "source_count": state.attributes.get("source_count"),
                "available_count": state.attributes.get("available_count"),
                "unavailable_count": state.attributes.get("unavailable_count"),
                "sources": aggregate_sources,
            }
        )
    return result


def _light_groups(hass: HomeAssistant, area: AdaptiveArea) -> list[dict[str, Any]]:
    """Map configured light groups; absent groups remain absent."""
    config = area.feature_config("light_groups")
    groups = []
    for key, label in _LIGHT_GROUPS.items():
        entity_ids = config.get(key, [])
        if not entity_ids:
            continue
        states = [hass.states.get(entity_id) for entity_id in entity_ids]
        groups.append(
            {
                "id": key,
                "name": label,
                "on": sum(
                    state is not None and state.state == STATE_ON for state in states
                ),
                "total": len(entity_ids),
                "sources": [
                    _state_data(hass.states.get(entity_id), entity_id)
                    for entity_id in entity_ids
                ],
            }
        )
    return groups


def _control(hass: HomeAssistant, entity_id: str) -> dict[str, Any]:
    """Map one explicitly configured light or integration switch control."""
    state = hass.states.get(entity_id)
    domain = entity_id.split(".", 1)[0]
    return {
        "entity_id": entity_id,
        "name": (
            state.attributes.get(ATTR_FRIENDLY_NAME, entity_id) if state else entity_id
        ),
        "domain": domain,
        "state": state.state if state else None,
        "available": state is not None
        and state.state not in (STATE_UNAVAILABLE, STATE_UNKNOWN),
        "controllable": domain in {"light", "switch"},
        "actions": ["turn_on", "turn_off"],
        "icon": state.attributes.get(ATTR_ICON) if state else None,
    }


def _controls(hass: HomeAssistant, area: AdaptiveArea) -> list[dict[str, Any]]:
    """Return deduplicated controls already assigned to a non-meta Area."""
    if area.is_meta():
        return []
    seen: set[str] = set()
    groups = []
    for group in _light_groups(hass, area):
        controls = [
            _control(hass, entity_id)
            for entity_id in area.feature_config("light_groups").get(group["id"], [])
            if entity_id not in seen and not seen.add(entity_id)
        ]
        if controls:
            groups.append(
                {"id": group["id"], "name": group["name"], "controls": controls}
            )
    switches = [
        _control(hass, entry["entity_id"])
        for entry in area.adaptive_entities.get("switch", [])
        if entry.get("entity_id") not in seen and not seen.add(entry["entity_id"])
    ]
    if switches:
        groups.append({"id": "switches", "name": "Controls", "controls": switches})
    return groups


def _environment(hass: HomeAssistant, area: AdaptiveArea) -> dict[str, Any] | None:
    """Return the public environment presentation, if the feature has data."""
    for entity in _generated_states(hass, area):
        state = hass.states.get(entity["entity_id"])
        if state is None or "notices" not in state.attributes:
            continue
        return {
            **entity,
            **{
                key: state.attributes[key]
                for key in (
                    "temperature",
                    "humidity",
                    "comfort",
                    "air_quality",
                    "mould_risk",
                    "notices",
                    "used_sensors",
                )
                if key in state.attributes
            },
        }
    return None


def _source_coverage(hass: HomeAssistant, entity_ids: list[str]) -> dict[str, int]:
    """Return the availability of already configured area sources."""
    states = [
        _state_data(hass.states.get(entity_id), entity_id) for entity_id in entity_ids
    ]
    return {
        "available": sum(state["available"] for state in states),
        "total": len(states),
    }


def _room_usage(area: AdaptiveArea) -> dict[str, Any] | None:
    """Return current, already calculated usage values."""
    if area.room_usage is None:
        return None
    assessment = area.room_usage.assessment
    return {
        key: assessment[key]
        for key in (
            "presence_minutes_since_cleaning",
            "current_occupancy_duration_seconds",
        )
        if key in assessment
    }


def _cleaning(area: AdaptiveArea) -> dict[str, Any] | None:
    """Return the existing cleaning assessment without recomputing it."""
    if area.room_usage is None:
        return None
    assessment = area.room_usage.assessment
    return {
        key: str(assessment[key]) if key == "cleaning_state" else assessment[key]
        for key in ("cleaning_state", "due", "remaining_minutes_to_due")
        if key in assessment
    }


def build_area_summary(hass: HomeAssistant, area: AdaptiveArea) -> dict[str, Any]:
    """Build the compact stable DTO used by the overview and update events."""
    aggregates = _aggregates(hass, area)
    illuminance = next(
        (item for item in aggregates if item.get("device_class") == "illuminance"), None
    )
    groups = _light_groups(hass, area)
    presence_sources = area.get_presence_sensors()
    sources = _area_sources(area)
    dark_source_id = area.config.get(CONF_DARK_ENTITY)
    dark_source = (
        _state_data(hass.states.get(dark_source_id), dark_source_id)
        if dark_source_id
        else None
    )
    brightness_state = (
        AREA_STATE_BRIGHT
        if area.has_state(AREA_STATE_BRIGHT)
        else AREA_STATE_DARK if area.has_state(AREA_STATE_DARK) else None
    )
    warning_count = sum(aggregate.get("source_count") == 0 for aggregate in aggregates)
    if dark_source and (
        (dark_source["state"] == STATE_ON and brightness_state == AREA_STATE_DARK)
        or (dark_source["state"] == "off" and brightness_state == AREA_STATE_BRIGHT)
    ):
        warning_count += 1
    return {
        "id": str(area.id),
        "name": area.name,
        "type": "meta" if area.is_meta() else "area",
        "occupied": area.is_occupied(),
        "active_states": sorted(str(state) for state in area.states),
        "presence": {
            "state": "occupied" if area.is_occupied() else "clear",
            **_source_coverage(hass, presence_sources),
        },
        "brightness": (
            {
                "state": brightness_state,
                "illuminance": illuminance.get("state") if illuminance else None,
                "unit": illuminance.get("unit") if illuminance else None,
            }
            if illuminance
            or area.has_state(AREA_STATE_BRIGHT)
            or area.has_state(AREA_STATE_DARK)
            else None
        ),
        "warning_count": warning_count,
        "lights": (
            {
                "on": sum(group["on"] for group in groups),
                "total": sum(group["total"] for group in groups),
                "groups": [
                    {key: group[key] for key in ("id", "name", "on", "total")}
                    for group in groups
                ],
            }
            if groups
            else None
        ),
        "environment": _environment(hass, area),
        "room_usage": _room_usage(area),
        "cleaning": _cleaning(area),
        "sources": _source_coverage(hass, sources),
        "controls": _controls(hass, area),
        "enabled_features": sorted(area.config.get(CONF_ENABLED_FEATURES, {})),
    }


def build_area_detail(hass: HomeAssistant, area: AdaptiveArea) -> dict[str, Any]:
    """Build a read-only area DTO from current runtime data."""
    summary = build_area_summary(hass, area)
    aggregates = _aggregates(hass, area)
    dark_source_id = area.config.get(CONF_DARK_ENTITY)
    return {
        **summary,
        "presence": {
            "occupied": area.is_occupied(),
            "sources": [
                _state_data(hass.states.get(source), source)
                for source in area.get_presence_sensors()
            ],
        },
        "brightness_detail": {
            "state": summary["brightness"],
            "dark_source": (
                _state_data(hass.states.get(dark_source_id), dark_source_id)
                if dark_source_id
                else None
            ),
        },
        "light_groups": _light_groups(hass, area),
        "aggregates": aggregates,
        "environment": _environment(hass, area),
        "sources": [
            _state_data(hass.states.get(source), source)
            for source in _area_sources(area)
        ],
        "controls": summary["controls"],
    }


def build_light_runtime_status(
    hass: HomeAssistant, area: AdaptiveArea
) -> dict[str, Any]:
    """Build a read-only snapshot for the Light section of one Area form."""
    if not area.has_feature(CONF_FEATURE_LIGHT):
        return {"area_id": str(area.id), "light": {"enabled": False}}

    snapshot = light_source_snapshot(area)
    if snapshot is None:
        return {
            "area_id": str(area.id),
            "light": {
                "enabled": True,
                "presence": {"available": False, "occupied": None},
                "illuminance": {
                    "configured": False,
                    "available": False,
                    "value": None,
                },
                "policy": {"decision": "NO_ACTION", "reason": "policy_not_configured"},
                "override": {"mode": "NONE"},
                "vacancy": {"pending": False, "due_at": None},
                "targets": {"total": 0, "available": 0},
            },
        }

    try:
        policy_config = light_policy_config_from_feature(
            area.feature_config(CONF_FEATURE_LIGHT)
        )
    except ValueError:
        policy_config = None
    decision = evaluate_light_policy(snapshot, policy_config)
    manager = getattr(area, "light_runtime_manager", None)
    vacancy = manager.vacancy_state if manager is not None else None
    override = manager.override_state if manager is not None else None
    return {
        "area_id": str(area.id),
        "light": {
            "enabled": True,
            "presence": {
                "available": snapshot.presence_available,
                "occupied": snapshot.presence_state,
            },
            "illuminance": {
                "configured": snapshot.illuminance_entity_id is not None,
                "available": snapshot.illuminance_available,
                "value": snapshot.illuminance_value,
            },
            "policy": {
                "decision": decision.action.value.upper(),
                "reason": decision.reason.value,
            },
            "override": {
                "mode": (
                    override.mode.value.upper() if override is not None else "NONE"
                )
            },
            "vacancy": {
                "pending": bool(vacancy and vacancy.pending),
                "due_at": vacancy.due_at if vacancy and vacancy.pending else None,
            },
            "targets": {
                "total": len(snapshot.targets),
                "available": sum(target.available for target in snapshot.targets),
            },
        },
    }


def build_climate_runtime_status(
    hass: HomeAssistant, area: AdaptiveArea
) -> dict[str, Any]:
    """Build a read-only Climate Control runtime snapshot for one Area."""
    enabled = area.has_feature(CONF_FEATURE_CLIMATE_CONTROL)
    config = area.feature_config(CONF_FEATURE_CLIMATE_CONTROL) if enabled else {}
    target_entity = config.get(CONF_CLIMATE_CONTROL_ENTITY_ID)
    target_state = hass.states.get(target_entity) if target_entity else None
    target_available = target_state is not None and target_state.state not in (
        STATE_UNAVAILABLE,
        STATE_UNKNOWN,
    )
    relevant_states = [
        str(state)
        for state in area.states
        if state
        in {
            AreaStates.CLEAR,
            AreaStates.SLEEP,
            AreaStates.EXTENDED,
            AreaStates.OCCUPIED,
        }
    ]
    controller = getattr(area, "climate_control_switch", None) if enabled else None
    controller_on = bool(controller and controller.is_on)
    decision, configured_preset = (
        controller.runtime_decision() if controller else ("no_action", None)
    )
    return {
        "area_id": str(area.id),
        "enabled": enabled,
        "controller_on": controller_on,
        "target_entity": target_entity,
        "target_available": target_available,
        "area_states": relevant_states,
        "current_preset": (
            target_state.attributes.get(ATTR_PRESET_MODE) if target_available else None
        ),
        "occupancy_threshold": (
            config.get(
                CONF_CLIMATE_CONTROL_OCCUPANCY_THRESHOLD,
                DEFAULT_CLIMATE_CONTROL_OCCUPANCY_THRESHOLD,
            )
            if enabled
            else None
        ),
        "occupancy_pending": bool(controller and controller.occupancy_pending),
        "decision": decision,
        "configured_preset": configured_preset,
    }


def _areas(hass: HomeAssistant) -> Iterable[AdaptiveArea]:
    """Yield loaded areas only."""
    yield from iter_runtime_areas(hass)


def build_overview(hass: HomeAssistant) -> dict[str, Any]:
    """Build the complete lightweight overview without global entity discovery."""
    areas = sorted(_areas(hass), key=lambda area: area.name.casefold())
    summaries = [build_area_summary(hass, area) for area in areas]
    return {
        "areas": summaries,
        "enabled_feature_tabs": sorted(
            {
                feature
                for summary in summaries
                for feature in summary["enabled_features"]
            }
        ),
        "counts": {
            "areas": sum(not area.is_meta() for area in areas),
            "meta_areas": sum(area.is_meta() for area in areas),
            "occupied": sum(area.is_occupied() for area in areas),
            "dark": sum(area.has_state(AREA_STATE_DARK) for area in areas),
            "bright": sum(area.has_state(AREA_STATE_BRIGHT) for area in areas),
            "lights_on": sum((item["lights"] or {}).get("on", 0) for item in summaries),
        },
    }


def build_diagnostics(hass: HomeAssistant, version: str | None) -> dict[str, Any]:
    """Report simple read-only dashboard diagnostics."""
    areas = list(_areas(hass))
    issues = []
    adaptive_entity_count = 0
    unavailable = 0
    for area in areas:
        try:
            detail = build_area_detail(hass, area)
        except Exception:  # Diagnostics must not hide every other Area.
            _LOGGER.exception(
                "Unable to build dashboard diagnostics for area %s", area.id
            )
            issues.append(
                {
                    "severity": "warning",
                    "area_id": str(area.id),
                    "code": "diagnostics_unavailable",
                    "message": "Some diagnostics are unavailable.",
                }
            )
            continue
        adaptive_entity_count += len(_generated_states(hass, area))
        unavailable += sum(not source["available"] for source in detail["sources"])
        for aggregate in detail["aggregates"]:
            if aggregate["source_count"] == 0:
                issues.append(
                    {
                        "severity": "warning",
                        "area_id": detail["id"],
                        "code": "empty_aggregate",
                        "message": "Aggregate has no sources.",
                    }
                )
        if detail["brightness_detail"]["dark_source"]:
            source = detail["brightness_detail"]["dark_source"]
            states = detail["active_states"]
            if (source["state"] == STATE_ON and AREA_STATE_DARK in states) or (
                source["state"] == "off" and AREA_STATE_BRIGHT in states
            ):
                issues.append(
                    {
                        "severity": "warning",
                        "area_id": detail["id"],
                        "code": "brightness_state_inconsistent",
                        "message": "Dark source and area brightness state disagree.",
                    }
                )
        issues.extend(
            {
                "severity": "warning",
                "area_id": detail["id"],
                "code": "unavailable_source",
                "message": "A source is unavailable.",
            }
            for source in detail["sources"]
            if not source["available"]
        )
    return {
        "version": version,
        "area_count": sum(not area.is_meta() for area in areas),
        "meta_area_count": sum(area.is_meta() for area in areas),
        "adaptive_entity_count": adaptive_entity_count,
        "unavailable_source_count": unavailable,
        "empty_aggregate_count": sum(
            issue["code"] == "empty_aggregate" for issue in issues
        ),
        "warning_count": len(issues),
        "issues": issues,
    }
